const express = require("express");
const router = express.Router();
const { verifyToken } = require("../../middleware/authMiddleware");
const { controller: c } = require("../controllers");
router.use(verifyToken);
router.post("/signals", c.ingestSignals);
router.post("/warmup", c.warmup);
router.post("/baseline/build", c.baseline);
router.post("/baseline/refresh", c.refresh);
router.get("/progress/overview", c.overview);
router.get("/progress/per-type", c.perType);
router.get("/progress/comparison", c.comparison);
router.get("/session/:sessionId", c.session);
router.get("/session/:sessionId/questions", c.questions);
router.get("/session/:sessionId/findings", c.findings);
router.get("/drift", c.drift);
router.post("/coaching/:sessionId/generate", c.coaching);
